/// SOFTMAX-I (spec v0.3): integer softmax over attention scores on the
/// Q40.24 score grid, producing Q0.15 probabilities.
///
/// Steps, all exact-integer:
///   1. `m = max(scores)` — exact i64 compare;
///   2. `e_t = exp_neg_q31((m − s_t) << 8)` (Q.24 → Q.32 arg is an exact
///      shift; the max element gets e = 2^31 exactly);
///   3. `S = Σ e_t` in i64 (≤ T · 2^31, exact for T ≤ 2^32);
///   4. `p_t = rne(e_t · 2^15 / S)` — RNE division, Q0.15.
///
/// `scores` is overwritten with the intermediate `e_t` values (the caller's
/// score buffer doubles as exp scratch — the engine is zero-allocation).
///
/// Declared bounds (property-tested):
///   - sum-to-one: `|Σ p_t − 2^15| ≤ ⌈T/2⌉` (each p carries ≤ 1/2 ulp of
///     RNE error and the e_t normalize exactly against their own sum);
///   - monotone: `s_i ≥ s_j ⇒ p_i ≥ p_j` (exact, from exp_neg_q31's
///     monotonicity and the shared divisor);
///   - underflow: a score more than ~21.49 real units below the max (Q.24:
///     z ≥ 31·2^32 in the exp argument) gets p = 0 exactly. The discarded
///     tail mass is < T·e^(−21.49) < 2.4e−7 for T ≤ 512 — below one Q0.15
///     ulp, i.e. below the output's own resolution.
pub fn softmax_i(scores: &mut [i64], probs: &mut [i32], lut: &ExpLut) {
    let n = scores.len();
    assert!(n > 0, "softmax_i: empty scores");
    assert!(
        n <= 1 << 20,
        "softmax_i: sequence too long for exact i64 sum"
    );
    assert!(probs.len() >= n, "softmax_i: probs buffer too short");
    let m = *scores.iter().max().unwrap();
    for s in scores.iter_mut() {
        let z = (m - *s) as u128; // ≥ 0, exact
        *s = exp_neg_q31(z << 8, lut); // Q.24 → Q.32 argument, exact shift
    }
    let mut sum: i64 = 0;
    for &e in scores.iter() {
        sum += e;
    }
    debug_assert!(
        sum >= 1 << 31,
        "softmax_i: max element must contribute 2^31"
    );
    for (p, &e) in probs.iter_mut().zip(scores.iter()) {
        *p = rne_div((e as i128) << 15, sum as i128) as i32;
    }
}

