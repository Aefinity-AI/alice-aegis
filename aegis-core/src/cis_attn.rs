/// 2π in Q2.62: `rne(2π · 2^62)`.
pub const TWO_PI_Q62: u128 = 28976077832308491370;
/// π in Q2.62: `rne(π · 2^62)`.
pub const PI_Q62: u128 = 14488038916154245685;
/// π/2 in Q2.62: `rne(π/2 · 2^62)`.
pub const PI_2_Q62: u128 = 7244019458077122842;
/// log2(e) in Q32.32: `rne(2^32 / ln 2)`.
pub const LOG2E_Q32: i64 = 6196328019;

// ---------------------------------------------------------------------------
// exp2 machinery: the floor-isqrt chain and the normative 1025-entry LUT.
// ---------------------------------------------------------------------------

/// Chain constants `C[k] = 2^(−2^(−k))` in Q0.62, k = 1..=32, generated by
/// the parameter-free normative procedure: `C[0] = 2^61` (= 1/2), then
/// `C[k] = isqrt(C[k−1] · 2^62)` (floor integer square root — exact, unique,
/// nothing to freeze). `C[0]` is the seed, not itself used as a factor.
pub fn exp2_chain() -> [u64; 33] {
    let mut c = [0u64; 33];
    c[0] = 1 << 61;
    for k in 1..=32 {
        c[k] = (((c[k - 1] as u128) << 62).isqrt()) as u64;
    }
    c
}

/// `2^(−f)` for `f` in Q0.32 ∈ [0, 2^32), result Q0.62 ∈ (2^61, 2^62].
/// Product over the set bits of `f` of the chain constants, RNE-requantized
/// to Q0.62 after each multiply (bit k of the fraction, MSB first, selects
/// `C[k]`). Used at table-generation time only (LUT + RoPE inv-freq), where
/// consecutive arguments are far apart, so its last-ulp non-monotonicity
/// can never surface in a table.
pub fn exp2_neg_frac(f_q32: u64, chain: &[u64; 33]) -> u128 {
    debug_assert!(f_q32 < 1 << 32);
    let mut acc: u128 = 1 << 62;
    for (k, &c) in chain.iter().enumerate().take(33).skip(1) {
        if (f_q32 >> (32 - k)) & 1 == 1 {
            acc = rne_div((acc * c as u128) as i128, 1 << 62) as u128;
        }
    }
    acc
}

/// The normative exp LUT: `E[i] = rne(2^(−i/1024) · 2^31)` for i = 0..1024
/// via the chain, plus the exact endpoint `E[1024] = 2^30`. Entries are
/// strictly decreasing (the function drops ≈ 1.45M Q0.31 ulps per entry;
/// chain + rounding error is a few ulps), which makes interpolated lookup
/// provably monotone.
pub struct ExpLut {
    e: Vec<i64>,
}

impl ExpLut {
    pub fn new() -> ExpLut {
        let chain = exp2_chain();
        let mut e = Vec::with_capacity(1025);
        for i in 0..1024u64 {
            e.push(rne_div(exp2_neg_frac(i << 22, &chain) as i128, 1 << 31) as i64);
        }
        e.push(1 << 30);
        ExpLut { e }
    }

    /// Entry access for goldens/digests.
    pub fn entry(&self, i: usize) -> i64 {
        self.e[i]
    }

    /// `2^(−f)` for `f` in Q0.32 ∈ [0, 2^32), Q0.31 ∈ [2^30, 2^31], by
    /// linear interpolation between the two straddling entries (top 10 bits
    /// index, low 22 bits interpolate). Monotone non-increasing in `f`:
    /// each segment is linear with a non-positive slope and segments join
    /// continuously at the entries.
    pub fn exp2_neg(&self, f_q32: u64) -> i64 {
        debug_assert!(f_q32 < 1 << 32);
        let i = (f_q32 >> 22) as usize;
        let r = (f_q32 & ((1 << 22) - 1)) as i128;
        let a = self.e[i];
        let b = self.e[i + 1];
        a - rne_div((a - b) as i128 * r, 1 << 22) as i64
    }
}

impl Default for ExpLut {
    fn default() -> Self {
        ExpLut::new()
    }
}

/// `e^(−z)` for `z ≥ 0` in Q32.32 (as u128 so callers with wide integer
/// grids never overflow), result Q0.31 ∈ [0, 2^31]. Route through base 2:
/// `y = z · log2(e)` (exact product, Q.64), split into integer part `n`
/// and RNE-rounded Q0.32 fraction `f`, then `E(f) / 2^n`. `n ≥ 31` (i.e.
/// `z > ~21.49`) underflows to exactly 0.
///
/// Monotone non-increasing in `z`: `y` is an exact monotone map, the
/// `(n, f)` split with the carry fold is lexicographically monotone with
/// continuous boundaries (`f → 2^32` folds to `(n+1, 0)`, and
/// `E(2^32) = E(0)/2` by the endpoint entry), `exp2_neg` is monotone, and
/// division by `2^n` preserves it. The property test asserts this.
pub fn exp_neg_q31(z_q32: u128, lut: &ExpLut) -> i64 {
    let y = z_q32 * LOG2E_Q32 as u128; // Q.64; callers keep z < 2^68
    let mut n = (y >> 64) as u32;
    if n >= 31 {
        return 0;
    }
    let mut f = rne_div((y & ((1u128 << 64) - 1)) as i128, 1 << 32) as u64;
    if f == 1 << 32 {
        n += 1;
        f = 0;
        if n >= 31 {
            return 0;
        }
    }
    rne_div(lut.exp2_neg(f) as i128, 1 << n) as i64
}

