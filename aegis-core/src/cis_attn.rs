/// `log2(value)` of a finite f32 with value ≥ 2, in Q32.32, by the
/// normative shift-and-square procedure: decompose the bit pattern into
/// `M · 2^E` with `M ∈ [1, 2)` held in Q2.62, then extract 32 fraction bits
/// by repeated squaring (RNE requant to Q2.62 each step; a renormalizing
/// halving — also RNE — emits a 1 bit). Integer-only, parameter-free.
pub fn log2_q32_f32(bits: u32) -> u64 {
    let exp = ((bits >> 23) & 0xFF) as i32;
    let man = bits & 0x7F_FFFF;
    assert!(
        bits >> 31 == 0 && exp != 0xFF && exp >= 128,
        "log2_q32_f32: RoPE base must be finite and >= 2"
    );
    let e = (exp - 127) as u64;
    let mut m: u128 = ((man as u128) | (1 << 23)) << 39; // Q2.62 ∈ [2^62, 2^63)
    let mut frac: u64 = 0;
    for _ in 0..32 {
        m = rne_div((m * m) as i128, 1 << 62) as u128;
        frac <<= 1;
        if m >= 1 << 63 {
            m = rne_div(m as i128, 2) as u128;
            frac |= 1;
        }
    }
    (e << 32) | frac
}

/// `(sin x, cos x)` for `x ∈ [0, 2π)` in Q2.62, results signed Q0.62.
///
/// Normative procedure: quadrant reduction against the pinned π constants
/// (`sin(x+π) = −sin x`; `sin(π−x) = sin x, cos(π−x) = −cos x`; a reduction
/// that lands 1 ulp below 0 saturates to 0), then 9-term Taylor sums on
/// [0, π/2] in Q0.62 with RNE requant after each multiply and exact integer
/// factorial divisors — no free coefficients exist. Truncation < 2^−40,
/// accumulated rounding ≲ 40 ulps of 2^−62: error is far below the Q1.30
/// table quantization that consumes these values.
pub fn sincos_q62(x: u128) -> (i64, i64) {
    debug_assert!(
        x < TWO_PI_Q62,
        "sincos_q62: argument must be reduced mod 2π"
    );
    let mut x = x;
    let mut sign_s: i128 = 1;
    let mut sign_c: i128 = 1;
    if x >= PI_Q62 {
        x -= PI_Q62;
        sign_s = -1;
        sign_c = -1;
    }
    if x >= PI_2_Q62 {
        x = PI_Q62.saturating_sub(x).min(PI_2_Q62);
        sign_c = -sign_c;
    }
    let xi = x as i128; // ≤ π/2 · 2^62 < 2^63
    let x2 = rne_div(xi * xi, 1 << 62); // Q0.62, ≤ ~2.47 · 2^62

    let mut t = xi;
    let mut s = xi;
    for k in 1..9i128 {
        t = rne_div(t * x2, 1 << 62);
        t = rne_div(t, (2 * k) * (2 * k + 1));
        s += if k & 1 == 1 { -t } else { t };
    }

    let mut t: i128 = 1 << 62;
    let mut c: i128 = 1 << 62;
    for k in 1..9i128 {
        t = rne_div(t * x2, 1 << 62);
        t = rne_div(t, (2 * k - 1) * (2 * k));
        c += if k & 1 == 1 { -t } else { t };
    }

    ((s * sign_s) as i64, (c * sign_c) as i64)
}

/// ROPE-I tables: Q1.30 i32 sin/cos per (position, frequency), generated at
/// load by the normative integer-only procedure — the same bits on every
/// platform, so the TABLE is reproducible from (max_seq, head_dim,
/// base_bits) alone and its FNV digest is golden-tested.
///
/// Generation rule per (pos, d), d < head_dim/2:
///   1. `L = log2_q32_f32(base_bits)`;
///   2. `a_d = rne(2d · L / head_dim)` (Q.32) — the exponent of the
///      inverse frequency `base^(−2d/head_dim) = 2^(−a_d)`;
///   3. `inv_freq_d = rne(exp2_neg_frac(frac(a_d)) / 2^int(a_d))` (Q0.62,
///      via the chain — absolute error ≤ ~2^−62, so even pos·error stays
///      below 2^−52 rad);
///   4. `θ = pos · inv_freq_d` (exact), reduced `θ mod TWO_PI_Q62`;
///   5. `(sin, cos) = sincos_q62(θ)`, RNE-requantized to Q1.30 and clamped
///      to ±2^30 (cos 0 = +2^30 exactly).
pub struct RopeTableI {
    pub cos: Vec<i32>,
    pub sin: Vec<i32>,
    pub max_seq: usize,
    pub half_dim: usize,
}

impl RopeTableI {
    pub fn new(max_seq: usize, head_dim: usize, base_bits: u32) -> RopeTableI {
        assert!(
            head_dim >= 2 && head_dim.is_multiple_of(2),
            "RoPE needs an even head_dim"
        );
        let half = head_dim / 2;
        let chain = exp2_chain();
        let l = log2_q32_f32(base_bits);
        let mut inv_freq: Vec<u128> = Vec::with_capacity(half); // Q0.62
        for d in 0..half {
            let a = rne_div(2 * d as i128 * l as i128, head_dim as i128) as u64;
            let n = a >> 32;
            let f = a & 0xFFFF_FFFF;
            assert!(n < 62, "RoPE-I: inverse frequency underflows Q0.62");
            inv_freq.push(rne_div(exp2_neg_frac(f, &chain) as i128, 1i128 << n) as u128);
        }
        let mut cos = Vec::with_capacity(max_seq * half);
        let mut sin = Vec::with_capacity(max_seq * half);
        for pos in 0..max_seq {
            for &ivf in &inv_freq {
                let theta = pos as u128 * ivf; // ≤ max_seq · 2^62, exact
                let r = theta % TWO_PI_Q62;
                let (s, c) = sincos_q62(r);
                cos.push(rne_div(c as i128, 1 << 32).clamp(-(1 << 30), 1 << 30) as i32);
                sin.push(rne_div(s as i128, 1 << 32).clamp(-(1 << 30), 1 << 30) as i32);
            }
        }
        RopeTableI {
            cos,
            sin,
            max_seq,
            half_dim: half,
        }
    }
}

/// ROPE-I rotation over fixed-point q/k (any common Q.f grid; the engine
/// uses Q.16). Same pairing as the production `attention::apply_rope`
/// (d, d + half_dim), arithmetic `rne((q0·cos − q1·sin) / 2^30)` in i64/i128
/// intermediates. Requires |q|, |k| < 2^30 so the rotated values (≤ √2·|q|
/// + 1 ulp) still fit i32; the engine's rescale asserts a stricter 2^29.
pub fn rope_apply_i(
    q: &mut [i32],
    k: &mut [i32],
    seq_pos: usize,
    num_heads: usize,
    num_kv_heads: usize,
    head_dim: usize,
    tab: &RopeTableI,
) {
    if seq_pos >= tab.max_seq {
        return;
    }
    let half = head_dim / 2;
    debug_assert_eq!(half, tab.half_dim);
    let off = seq_pos * half;
    let rotate = |v: &mut [i32]| {
        for d in 0..half {
            let c = tab.cos[off + d] as i128;
            let s = tab.sin[off + d] as i128;
            let v0 = v[d] as i128;
            let v1 = v[d + half] as i128;
            v[d] = rne_div(v0 * c - v1 * s, 1 << 30) as i32;
            v[d + half] = rne_div(v0 * s + v1 * c, 1 << 30) as i32;
        }
    };
    for h in 0..num_heads {
        rotate(&mut q[h * head_dim..(h + 1) * head_dim]);
    }
    for h in 0..num_kv_heads {
        rotate(&mut k[h * head_dim..(h + 1) * head_dim]);
    }
}

/// `1/sqrt(n)` in Q0.30 by the parameter-free rule
/// `rne(2^60 / isqrt(n · 2^60))` — exact for power-of-four n (head_dim 64
/// gives exactly 2^27 = 0.125). Used to scale attention scores.
pub fn inv_sqrt_q30(n: u64) -> i64 {
    assert!(n > 0, "inv_sqrt_q30: n must be positive");
    let s = ((n as u128) << 60).isqrt(); // floor(sqrt(n) · 2^30)
    rne_div(1i128 << 60, s as i128) as i64
}

