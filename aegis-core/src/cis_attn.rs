//! CIS-1 v0.3 — the integer attention & activation organs: ROPE-I,
//! SOFTMAX-I, ACT-I.
//!
//! Spec: `docs/CIS-1_SPEC_DRAFT_v0.1.md`, "v0.3 integer-attention notes".
//! These ops close E2's declared hybrid gap: with them, `cis_infer`'s
//! FULL-INTEGER mode runs the entire forward pass in exact integer /
//! fixed-point arithmetic — no float value ever enters the computation, so
//! cross-kernel-path and cross-ISA bit-identity holds BY CONSTRUCTION
//! (every loop below is scalar integer Rust; there is no SIMD dispatch to
//! diverge from).
//!
//! Everything here is `core`-only integer arithmetic — no floats, no
//! `libm`, no `unsafe`. All rounding goes through `cis::rne_div`
//! (round-half-even), the module's single rounding primitive. Every
//! normative constant is either a pinned integer literal (π, log2 e — from
//! published decimal expansions) or the output of a parameter-free integer
//! procedure (floor `isqrt` chains, squaring-based log2, Taylor sums with
//! exact factorial divisors). Golden tests pin the constants against the
//! INDEPENDENT Python big-int generator (`scripts/cis_e2_golden_gen.py`).

