    #[test]
    fn golden_rope_table_m7() {
        // M7 shape: head_dim 64, seq 512, base 10000.0.
        let t = RopeTableI::new(512, 64, 10000.0f32.to_bits());
        // pos 0: identity rotation for every frequency.
        for d in 0..32 {
            assert_eq!((t.cos[d], t.sin[d]), (1 << 30, 0), "pos 0 d {d}");
        }
        // Spot goldens from the independent generator.
        assert_eq!((t.cos[32], t.sin[32]), (580145183, 903522590)); // pos 1, d 0
        assert_eq!((t.cos[63], t.sin[63]), (1073741814, 143186)); // pos 1, d 31
        assert_eq!(
            (t.cos[100 * 32 + 7], t.sin[100 * 32 + 7]),
            (771714489, 746577693)
        );
        assert_eq!(
            (t.cos[511 * 32 + 31], t.sin[511 * 32 + 31]),
            (1071249849, 73111318)
        );
        // Whole-table digest: cos then sin, LE i32, per (pos, d).
        let mut d = FNV1A64_OFFSET;
        for i in 0..512 * 32 {
            d = fnv1a64(d, &t.cos[i].to_le_bytes());
            d = fnv1a64(d, &t.sin[i].to_le_bytes());
        }
        assert_eq!(d, 0xD8345EBF01E990FA);
    }

