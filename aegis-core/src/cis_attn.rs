    /// σ seam: both sign branches at g = ±1 (smallest Q.20 ulp) bracket the
    /// g = 0 value monotonically; the RNE ties at |σ·g| ≈ 0.5 ulp resolve
    /// to at most one output ulp (goldens from the generator).
    #[test]
    fn silu_sign_seam() {
        let lut = ExpLut::new();
        let a = silu_q20(-1, 1 << 20, &lut);
        let b = silu_q20(0, 1 << 20, &lut);
        let c = silu_q20(1, 1 << 20, &lut);
        assert_eq!((a, b, c), (0, 0, 1));
        assert!(a <= b && b <= c, "silu seam not monotone: {a} {b} {c}");
    }
