/// Integer relu²·up on the Q.20 grid: `rne(max(0, g)² / 2^20) · u`,
/// RNE-requantized back to Q.20. Exact up to the two declared RNE requants;
/// intermediates in i128 (callers assert |g|, |u| < 2^40, so the final
/// product magnitude is < 2^80 and the i64 assert below is the loud guard).
pub fn relu2_q20(g: i64, u: i64) -> i64 {
    if g <= 0 {
        return 0;
    }
    let a = rne_div(g as i128 * g as i128, 1 << 20); // Q.20
    let r = rne_div(a * u as i128, 1 << 20);
    assert!(
        r >= i64::MIN as i128 && r <= i64::MAX as i128,
        "relu2_q20: result exceeds i64"
    );
    r as i64
}

/// Integer silu(g)·up on the Q.20 grid.
///
/// `σ(g)` in Q0.31 via the exp LUT; both sign branches evaluate one exp of
/// `t = e^(−|g|)` so the argument is always non-negative:
///   g ≥ 0: `σ = rne(2^62 / (2^31 + t))`
///   g < 0: `σ = rne(t · 2^31 / (2^31 + t))`
/// (both are the same real function 1/(1+e^(−g)); at g = 0 both give
/// exactly 2^30 = 1/2, so the seam is continuous).
/// Then `silu = rne(g · σ / 2^31)` (Q.20) and `out = rne(silu · u / 2^20)`.
pub fn silu_q20(g: i64, u: i64, lut: &ExpLut) -> i64 {
    debug_assert!(
        g.unsigned_abs() < 1 << 40 && u.unsigned_abs() < 1 << 40,
        "silu_q20: inputs exceed the Q.20 headroom contract"
    );
    let sig_q31: i128 = if g >= 0 {
        let t = exp_neg_q31((g as u128) << 12, lut); // Q.20 → Q.32 arg
        rne_div(1i128 << 62, (1i128 << 31) + t as i128)
    } else {
        let t = exp_neg_q31((g.unsigned_abs() as u128) << 12, lut);
        rne_div((t as i128) << 31, (1i128 << 31) + t as i128)
    };
    let s = rne_div(g as i128 * sig_q31, 1 << 31); // Q.20
    let r = rne_div(s * u as i128, 1 << 20);
    assert!(
        r >= i64::MIN as i128 && r <= i64::MAX as i128,
        "silu_q20: result exceeds i64"
    );
    r as i64
}

